#!/usr/bin/env python3
"""Runs the two steps of dependency-snapshot.yml: the build on requirements files in throwaway
folders, and the submission against a stand-in for gh.

Usage: test_dependency_snapshot.py [WORKFLOW]   (default: .github/workflows/dependency-snapshot.yml)
       test_dependency_snapshot.py [--step SCRIPT] [--submit-step SCRIPT]
                                   (already extracted scripts, for a deliberately broken copy)

Needs yq (mikefarah), jq and bash. Nothing talks to GitHub.
"""
import collections
import json
import pathlib
import re
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
WORKFLOW = HERE.parents[1] / ".github" / "workflows" / "dependency-snapshot.yml"
SHA = "0123456789abcdef0123456789abcdef01234567"
NEWER = "89abcdef0123456789abcdef0123456789abcdef"
APP = "requirements/app.txt"
PATH = "/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin"
Steps = collections.namedtuple("Steps", "build submit")

# As `uv pip compile --generate-hashes` writes a lock.
LOCK = """\
# This file was autogenerated by uv via the following command:
#    uv pip compile requirements/app.in --generate-hashes -o requirements/app.txt
dnspython==2.9.2 \\
    --hash=sha256:aaaa \\
    --hash=sha256:bbbb
    # via -r requirements/app.in
Ruamel.Yaml_clib==0.2.12 ; platform_python_implementation == "CPython" and python_version < "3.14" \\
    --hash=sha256:cccc
    # via ruamel-yaml
"""

# pip 26.2.2 and 21.2.4 read these lines this way (pip._internal.req.req_file.preprocess), and so
# does uv 0.13.7, except that it rejects a marker on a continuation line and a backslash at the end
# of the file. A comment line never continues, even when it ends in a backslash.
TRICKY = """\
Foo_Bar.baz[extra1, extra2] == 1.0+local  # inline comment
# a comment that ends in a backslash \\
kept==2.0
joined==3.0 \\
; python_version >= "3.12"
end==7.0 \\
    --hash=sha256:aaaa \\
    --hash=sha256:bbbb
    # via -r x.in \\
after==9.0
last==8.0 \\
"""

# A stand-in for gh: logs its arguments, answers the head lookup with FAKE_HEAD and the snapshot
# POST with FAKE_RESPONSE, or fails that POST when FAKE_POST_FAILS is set.
FAKE_GH = """\
#!{python}
import json, os, pathlib, sys
args = sys.argv[1:]
with open(os.environ["FAKE_LOG"], "a") as f:
    f.write(json.dumps(args) + "\\n")
if "--method" in args:
    if not pathlib.Path(args[args.index("--input") + 1]).is_file():
        sys.exit("gh: no input file")
    if os.environ.get("FAKE_POST_FAILS"):
        sys.exit("gh: HTTP 422: Unprocessable Entity")
    print(os.environ["FAKE_RESPONSE"])
else:
    print(os.environ["FAKE_HEAD"])
"""

SCENARIOS = []


def scenario(fn):
    SCENARIOS.append(fn)
    return fn


def run(root, step, files, runtime=APP, development="", correlator="pinned-requirements", links=None):
    """Runs the build step in a throwaway repository holding files: (exit code, output, snapshot or None)."""
    repo, temp = root / "repo", root / "runner-temp"
    repo.mkdir()
    temp.mkdir()
    for path, content in files.items():
        (repo / path).parent.mkdir(parents=True, exist_ok=True)
        (repo / path).write_text(content)
    for path, target in (links or {}).items():
        (repo / path).parent.mkdir(parents=True, exist_ok=True)
        (repo / path).symlink_to(target)
    env = {
        "PATH": "/usr/bin:/bin", "RUNTIME_FILES": runtime, "DEVELOPMENT_FILES": development,
        "CORRELATOR": correlator, "GITHUB_SHA": SHA, "GITHUB_REF": "refs/heads/main", "GITHUB_RUN_ID": "42",
        "GITHUB_SERVER_URL": "https://github.com", "GITHUB_REPOSITORY": "owner/repo", "RUNNER_TEMP": str(temp),
    }
    r = subprocess.run([sys.executable, "-I", str(step.build)], cwd=repo, env=env, capture_output=True, text=True)
    out = temp / "dependency-snapshot.json"
    return r.returncode, r.stdout + r.stderr, json.loads(out.read_text()) if out.exists() else None


def submit(root, step, answer=None, *, ref="refs/heads/main", default="main", head=SHA, post_fails=False):
    """Runs the submit step against the stand-in for gh: (exit code, output, whether it posted)."""
    (root / "bin").mkdir()
    gh = root / "bin" / "gh"
    gh.write_text(FAKE_GH.format(python=sys.executable))
    gh.chmod(0o755)
    (root / "runner-temp").mkdir()
    (root / "runner-temp" / "dependency-snapshot.json").write_text("{}\n")
    log = root / "gh.log"
    env = {
        "PATH": f"{root / 'bin'}:{PATH}", "RUNNER_TEMP": str(root / "runner-temp"), "REPO": "owner/repo",
        "REF": ref, "SHA": SHA, "DEFAULT_BRANCH": default, "FAKE_LOG": str(log), "FAKE_HEAD": head,
        "FAKE_RESPONSE": json.dumps(answer if answer is not None else {}),
    }
    if post_fails:
        env["FAKE_POST_FAILS"] = "1"
    r = subprocess.run(["bash", str(step.submit)], env=env, capture_output=True, text=True)
    calls = [json.loads(line) for line in log.read_text().splitlines()] if log.exists() else []
    return r.returncode, r.stdout + r.stderr, any("--method" in c for c in calls)


def answer(result, message="Dependency results for the repo have been successfully updated."):
    return {"id": 7, "created_at": "2026-11-14T17:00:00Z", "result": result, "message": message}


def ok(result, manifests):
    """manifests: {path: (scope, {package URL})}, exactly what the snapshot must list."""
    code, output, snapshot = result
    if code != 0 or snapshot is None:
        return [f"exit {code}, snapshot {'written' if snapshot else 'missing'}: {output.strip()[-300:]}"]
    problems = []
    if set(snapshot["manifests"]) != set(manifests):
        problems.append(f"manifests {sorted(snapshot['manifests'])}, expected {sorted(manifests)}")
    for path, (scope, expected) in manifests.items():
        m = snapshot["manifests"].get(path, {})
        if m.get("name") != path or m.get("file") != {"source_location": path}:
            problems.append(f"{path}: name or source_location wrong: {m.get('name')}, {m.get('file')}")
        resolved = m.get("resolved", {})
        if set(resolved) != expected:
            problems.append(f"{path}: {sorted(resolved)}, expected {sorted(expected)}")
        wrong = [k for k, v in resolved.items() if v != {"package_url": k, "scope": scope}]
        if wrong:
            problems.append(f"{path}: not {scope}, or the package URL differs from its key: {wrong}")
    return problems


def fails(result, says):
    code, output, snapshot = result
    problems = []
    if code == 0:
        problems.append("exit 0")
    if snapshot is not None:
        problems.append("a snapshot was written")
    if f"::error title=Dependency snapshot::{says}" not in output:
        problems.append(f"output lacks {says!r}: {output.strip()[-300:]}")
    return problems


def submitted(result, code, says, posted=True):
    problems = []
    if (result[0] == 0) != (code == 0):
        problems.append(f"exit {result[0]}, expected {'0' if code == 0 else 'non-zero'}")
    if says not in result[1]:
        problems.append(f"output lacks {says!r}: {result[1].strip()[-300:]}")
    if result[2] != posted:
        problems.append("posted" if result[2] else "did not post")
    return problems


@scenario
def s01_a_hash_locked_file_is_read_in_full(root, step):
    result = run(root, step, {APP: LOCK})
    problems = ok(result, {APP: ("runtime", {"pkg:pypi/dnspython@2.9.2", "pkg:pypi/ruamel-yaml-clib@0.2.12"})})
    snapshot = result[2] or {}
    expected = {
        "version": 0, "sha": SHA, "ref": "refs/heads/main",
        "job": {"correlator": "pinned-requirements", "id": "42", "html_url": "https://github.com/owner/repo/actions/runs/42"},
        "detector": {"name": "pinned-requirements", "version": "1",
                     "url": "https://github.com/agusgonzaleznic/github-reusable-workflows"},
    }
    for key, value in expected.items():
        if snapshot.get(key) != value:
            problems.append(f"{key}: {snapshot.get(key)!r}, expected {value!r}")
    if set(snapshot) != {*expected, "scanned", "manifests"}:
        problems.append(f"top-level keys {sorted(snapshot)}")
    if not re.fullmatch(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ", str(snapshot.get("scanned"))):
        problems.append(f"scanned: {snapshot.get('scanned')!r}")
    return problems


