def extract(workflow, name, dest):
    """Writes the run script of the step with this name to dest."""
    script = subprocess.run(["yq", "-r", f'.jobs.snapshot.steps[] | select(.name == "{name}") | .run', str(workflow)],
                            check=True, capture_output=True, text=True, env={"PATH": PATH}).stdout
    if len(script.strip()) < 100:
        sys.exit(f"No script found in the step named {name!r} of {workflow}")
    dest.write_text(script)
    return dest


def main():
    args = sys.argv[1:]
    opts = dict(zip(args[::2], args[1::2])) if args[:1] and args[0].startswith("--") else {}
    workflow = pathlib.Path(args[0]) if args and not opts else WORKFLOW
    failed = 0
    with tempfile.TemporaryDirectory(prefix="ds-step-") as scratch:
        s = pathlib.Path(scratch)
        step = Steps(
            pathlib.Path(opts["--step"]).resolve() if "--step" in opts else extract(workflow, "Build the snapshot", s / "build.py"),
            pathlib.Path(opts["--submit-step"]).resolve() if "--submit-step" in opts
            else extract(workflow, "Submit the snapshot", s / "submit.sh"))
        for fn in SCENARIOS:
            with tempfile.TemporaryDirectory(prefix="ds-") as tmp:
                try:
                    problems = fn(pathlib.Path(tmp).resolve(), step)
                except Exception as exc:  # a harness error counts as a failure
                    problems = [f"harness error: {exc!r}"]
            failed += bool(problems)
            print(f"{'FAIL' if problems else 'ok  '} {fn.__name__}" + ("  <- " + "; ".join(problems) if problems else ""))
    print(f"{len(SCENARIOS) - failed} of {len(SCENARIOS)} passed")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
